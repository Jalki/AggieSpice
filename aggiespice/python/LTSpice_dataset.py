import subprocess
import ltspice
import pandas as pd
import numpy as np
import random
import os
import sys

# -------------------------
# Function to run a SPICE simulation
# -------------------------
def run_sim(R_value, C_value, VDC_value, sim_id, analysis_type="AC"):

    # Load template
    with open("aggiespice/data/AI_Data/template_rc.cir", "r") as f:
        netlist = f.read()

    # Replace parameters
    modified = (
        netlist.replace("{Rval}", str(R_value))
               .replace("{Cval}", str(C_value))
               .replace("{VDC}", str(VDC_value))
    )

    sim_file = f"temp_sim_{sim_id}.cir"

    # Save modified netlist
    with open(sim_file, "w") as f:
        f.write(modified)

    try:
        # Run LTspice in batch mode (no GUI)
        subprocess.run([
            r"C:/Program Files/ADI/LTspice/LTspice.exe",
            "-Run",
            "-b",
            sim_file
        ], check=True)

        # Find the RAW file created by LTspice
        raw_files = [f for f in os.listdir('.') if f.endswith(".raw")]
        if not raw_files:
            raise FileNotFoundError("No RAW file generated by LTspice.")
        raw_file = raw_files[0]

        # Parse the RAW file
        l = ltspice.Ltspice(raw_file)
        l.parse()

        # Choose correct axis depending on analysis type
        if analysis_type.upper() == "AC":
            x_axis = l.get_frequency()
        elif analysis_type.upper() == "TRAN":
            x_axis = l.get_time()
        else:
            raise ValueError("analysis_type must be 'AC' or 'TRAN'")

        y_data = l.get_data("V(mid)")

    except ltspice.InvalidPhysicalValueRequestedException:
        print(f"⚠️  Simulation {sim_id} does not support {analysis_type} axis")
        x_axis = []
        y_data = []

    finally:
        # Cleanup temporary and LTspice files
        for f in os.listdir('.'):
            if f.endswith(".raw") or f.endswith(".log") or f.endswith(".cir") or f.endswith(".cir~"):
                os.remove(f)

    return x_axis, y_data


# -------------------------
# Procedural dataset generation with Ctrl+C support
# -------------------------

dataset = []
N_SAMPLES = 1000
ANALYSIS_TYPE = "AC"  # Change to "TRAN" if you want transient simulation

print("Press CTRL+C at any time to stop simulations safely.\n")

try:
    for i in range(N_SAMPLES):

        # Randomized RC parameters
        R = random.uniform(100, 10000)       # 100 Ω to 10k Ω
        C = random.uniform(1e-7, 1e-4)       # 0.1 uF to 100 uF
        VDC = random.uniform(1, 12)          # 1V to 12V supply

        x_axis, y_data = run_sim(R, C, VDC, i, ANALYSIS_TYPE)

        # Store magnitude or voltage data
        for x_val, y_val in zip(x_axis, y_data):
            dataset.append({
                "SimID": i,
                "R": R,
                "C": C,
                "VDC": VDC,
                "x": x_val,            # frequency (AC) or time (TRAN)
                "Vout": abs(y_val)
            })

        print(f"Finished simulation {i+1}/{N_SAMPLES}")

except KeyboardInterrupt:
    print("\n\n⚠️  Simulation manually stopped by user (CTRL+C).")
    print("Saving partial results...\n")

finally:
    # Save dataset regardless of interruption
    df = pd.DataFrame(dataset)
    df.to_csv("spice_dataset.csv", index=False)
    print("💾 Data saved to spice_dataset.csv")
    print("✅ Program exited safely.")
